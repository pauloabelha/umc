import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL||'http://127.0.0.1:5173';
const browser=await chromium.launch({args:['--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/simulator/?component=seven-instruction-lattice&mode=semantic&playback=fast`);
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
 assert.match(await page.locator('.triad-current').innerText(),/1 · INC\(a\)/);
 assert.match(await page.locator('.triad-previous').innerText(),/—/);
 assert.match(await page.locator('.triad-next').innerText(),/2 · JUMP\(5\)/);
 assert.equal(await page.locator('#instruction-strip span').count(),7);
 assert.deepEqual(await page.locator('#register-strip strong').allTextContents(),['0','0']);
 const triad=await page.locator('.instruction-triad').boundingBox(),toggle=await page.locator('#toggle-cells').boundingBox();
 assert.ok(triad.x+triad.width<toggle.x && Math.abs(triad.y-toggle.y)<2);
 const viewport=await page.locator('#viewport').boundingBox(),dashboard=await page.locator('#machine-dashboard').boundingBox();
 assert.ok(Math.abs(dashboard.y-viewport.y-viewport.height)<2);
 const before=await page.locator('#viewport').screenshot();
 await page.locator('#follow-marble').tap();
 assert.equal(await page.locator('#follow-marble').getAttribute('aria-pressed'),'true');
 assert.notDeepEqual(await page.locator('#viewport').screenshot(),before,'Follow must reposition the camera');
 assert.ok((await page.locator('.marble-halo').boundingBox()).width>36,'Follow zoom must enlarge the marble beyond the minimum halo');
 await page.locator('#follow-marble').tap();
 assert.deepEqual(await page.locator('#viewport').screenshot(),before,'Unfollow must restore the full-circuit camera');
 await page.locator('#follow-marble').tap();
 await page.locator('#run').tap();
 await page.waitForFunction(()=>document.querySelector('.triad-current strong').textContent==='5 · INC(a)');
 await page.locator('#run').tap();
 assert.match(await page.locator('.triad-previous').innerText(),/2 · JUMP\(5\)/);
 assert.match(await page.locator('.triad-next').innerText(),/6 · JUMP\(3\)/);
 assert.match(await page.locator('#instruction-strip [aria-current]').innerText(),/5 · INC/);
 await page.locator('#follow-marble').tap();
 assert.equal(await page.locator('#follow-marble').getAttribute('aria-pressed'),'false');
 await page.locator('#reset').tap();
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
 assert.deepEqual(await page.locator('#register-strip strong').allTextContents(),['0','0']);
 assert.match(await page.locator('.triad-previous').innerText(),/—/);
 await page.locator('#component').selectOption('closed-loop');
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
 assert.equal(await page.locator('.instruction-triad').isVisible(),false);
 assert.equal(await page.locator('#machine-dashboard').isVisible(),false);
 await page.goto(`${base}/simulator/?component=closed-loop`);
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
 assert.equal(await page.locator('#mode').inputValue(),'cpu');
 await page.goto(`${base}/simulator/logic.html?gate=xor`);
 await page.waitForFunction(()=>document.querySelector('#logic-status').textContent==='Ready');
 assert.equal(await page.locator('#logic-mode').inputValue(),'cpu');
 await page.locator('#logic-mode').selectOption('semantic');
 await page.waitForFunction(()=>document.querySelector('#logic-status').textContent==='Ready');
 await page.locator('#follow-marble').tap();
 await page.locator('#logic-step').tap();
 assert.equal(await page.locator('#follow-marble').getAttribute('aria-pressed'),'true');
 await page.locator('#follow-marble').tap();
 assert.deepEqual(errors,[]);
 console.log('PASS floating instruction sequence, register panel, reset, mobile placement, and follow camera in component/logic views');
} finally {await browser.close();}
