import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {physicalCatalog} from '../src/simulator/catalog.js';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const errors=[],checks=[];
await mkdir('artifacts',{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1280,height:950}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/simulator/?component=closed-loop&mode=semantic');
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent==='Ready');
  assert.deepEqual(await page.locator('#component option').evaluateAll(options=>options.map(o=>o.value)),physicalCatalog.map(item=>item.id));
  assert.equal(await page.locator('.browser-card').count(),19);
  assert.match(await page.locator('#composition-tree').textContent(),/Level 2/);
  assert.match(await page.locator('#composition-tree').textContent(),/Level 0/);
  for(let i=0;i<9;i++){await page.locator('#step').click();await page.waitForFunction(()=>!document.querySelector('#step').disabled);}
  assert.equal(await page.locator('#output').textContent(),'1 lap');
  assert.match(await page.locator('#execution-log').innerText(),/FerryElevator.elevator/);
  checks.push('shared browser, recursive hierarchy, complete semantic ramp lap');
  await page.locator('#component').selectOption('toggle-loop');
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
  for(let i=0;i<22;i++){await page.locator('#step').click();await page.waitForFunction(()=>!document.querySelector('#step').disabled);}
  assert.equal(await page.locator('#output').textContent(),'2 laps');
  const log=await page.locator('#execution-log').innerText();
  assert.match(log,/state left → right/);assert.match(log,/state right → left/);
  assert.match(log,/left-entry/);assert.match(log,/right-entry/);
  await page.locator('#reset').click();await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
  assert.equal(await page.locator('#gate-state').textContent(),'left');
  checks.push('both physical-topology branches, retained semantic memory and reset');
  await page.locator('#component').selectOption('seven-instruction-lattice');
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
  assert.match(await page.locator('#composition-tree').textContent(),/Level 3/);
  assert.equal(await page.locator('#program-rows tr').count(),7);
  await page.locator('#step').click();await page.waitForFunction(()=>document.querySelector('#status').textContent==='Paused');
  assert.match(await page.locator('#marble-rows').innerText(),/a-entry/);
  await page.locator('#scale').selectOption('0.5');await page.reload();
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
  assert.equal(await page.locator('#scale').inputValue(),'0.5');
  checks.push('seven-instruction assembly, stepping, URL settings');
  await page.locator('#component').selectOption('closed-loop');
  await page.locator('#mode').selectOption('cpu');
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Ready');
  await page.locator('#run').click();
  await page.waitForFunction(()=>parseInt(document.querySelector('#output').textContent,10)>=1,null,{timeout:30000});
  await page.locator('#run').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Paused');
  checks.push('CPU loop in browser, live lap readout, pause');
  await page.locator('.workspace').screenshot({path:'artifacts/simulator-desktop.png'});
  await page.route('http://127.0.0.1:8792/**',route=>route.abort());
  await page.locator('#mode').selectOption('gpu');await page.locator('#step').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Error');
  assert.equal(await page.locator('#mode').inputValue(),'gpu');
  assert.ok(await page.locator('#error').isVisible());
  checks.push('GPU failure remains visible without fallback');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'artifacts/simulator-mobile.png'});
  assert.deepEqual(errors,[]);
  await writeFile('artifacts/browser-results.json',JSON.stringify({passed:true,checks},null,2));
  console.log(checks);
}finally{await browser.close();}
